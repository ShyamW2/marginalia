import type { PageItems } from "./headerFooter.js";
import { stripRunningHeadersFooters } from "./headerFooter.js";
import { orderPageItems } from "./columns.js";
import { groupLines } from "./lines.js";
import { detectEquationBands } from "./equations.js";
import { detectFigureRegions } from "./figures.js";
import { buildPageBlocks } from "./blocks.js";
import { cropRegion, renderPageToBuffer, type RenderablePage } from "./rasterize.js";
import type { ExtractedPdf, PdfOutlineEntry, PdfPageContent, RawTextItem } from "./types.js";

const SCAN_CHAR_THRESHOLD = 100;
const SCAN_PAGE_FRACTION = 0.5;

export class PdfPasswordError extends Error {
  constructor() {
    super("PDF is password-protected");
    this.name = "PdfPasswordError";
  }
}

export class PdfInvalidError extends Error {
  constructor(cause?: unknown) {
    super("PDF is corrupt or not a readable PDF");
    this.name = "PdfInvalidError";
    if (cause instanceof Error) this.cause = cause;
  }
}

// Minimal shape of what we use from pdfjs-dist's document/page proxies —
// keeps the pdfjs-dist type surface confined to this file.
interface PdfjsTextItem {
  str: string;
  transform: number[];
  width: number;
  height: number;
  fontName: string;
}
interface PdfjsPage extends RenderablePage {
  getTextContent(): Promise<{ items: (PdfjsTextItem | Record<string, unknown>)[] }>;
}
interface PdfjsOutlineNode {
  title: string;
  dest: string | unknown[] | null;
  items: PdfjsOutlineNode[];
}
interface PdfjsDocument {
  numPages: number;
  getPage(n: number): Promise<PdfjsPage>;
  getOutline(): Promise<PdfjsOutlineNode[] | null>;
  getDestination(name: string): Promise<unknown[] | null>;
  getPageIndex(ref: unknown): Promise<number>;
  getMetadata(): Promise<{ info?: Record<string, unknown> }>;
}

function isTextItem(item: PdfjsTextItem | Record<string, unknown>): item is PdfjsTextItem {
  return typeof (item as PdfjsTextItem).str === "string" && Array.isArray((item as PdfjsTextItem).transform);
}

async function loadDocument(buffer: Buffer): Promise<PdfjsDocument> {
  const { getDocument } = await import("pdfjs-dist/legacy/build/pdf.mjs");
  try {
    const doc = (await getDocument({
      data: new Uint8Array(buffer),
      useSystemFonts: true,
    }).promise) as unknown as PdfjsDocument;
    return doc;
  } catch (err) {
    const name = err instanceof Error ? err.name : "";
    if (name === "PasswordException") throw new PdfPasswordError();
    throw new PdfInvalidError(err);
  }
}

async function resolveOutlineEntry(
  doc: PdfjsDocument,
  node: PdfjsOutlineNode,
): Promise<PdfOutlineEntry> {
  let dest = node.dest;
  if (typeof dest === "string") {
    dest = await doc.getDestination(dest).catch(() => null);
  }
  if (!Array.isArray(dest) || dest.length === 0) {
    return { title: node.title, pageIndex: null, y: null };
  }
  const [ref] = dest;
  let pageIndex: number | null = null;
  try {
    pageIndex = await doc.getPageIndex(ref);
  } catch {
    pageIndex = null;
  }
  return { title: node.title, pageIndex, y: destinationY(dest) };
}

/** A PDF destination array is `[page, /TypeName, ...coords]`, and where the
 *  "top" coordinate sits (or whether it exists at all) depends on the type
 *  (PDF 32000-1 §12.3.2.2). `/XYZ` and `/FitH`/`/FitBH` carry it at index 2;
 *  `/FitR`'s is its 4th coordinate; `/Fit`/`/FitB`/`/FitV`/`/FitBV` carry no
 *  top at all — found live at the M39 §A8 gate, where a book generated by
 *  pdfkit turned out to use `/Fit` throughout (NOTES.md "M39 §A8"), which a
 *  version of this function that assumed `/XYZ`'s shape silently read as
 *  null for every single entry. A real book/paper is more likely to use
 *  `/XYZ` (what LaTeX's hyperref and most PDF-export paths emit), but not
 *  guaranteed to. */
function destinationY(dest: unknown[]): number | null {
  const typeName = typeof dest[1] === "string" ? dest[1] : (dest[1] as { name?: string } | undefined)?.name;
  const at = (index: number): number | null => (typeof dest[index] === "number" ? (dest[index] as number) : null);
  switch (typeName) {
    case "XYZ":
    case "FitH":
    case "FitBH":
      return at(2);
    case "FitR":
      return at(4);
    default:
      return null;
  }
}

/** Flattens the outline tree in document order — PDF.md §4 doesn't
 *  distinguish nesting depth, and neither does the detected-headings
 *  fallback it stands in for. */
async function extractOutline(doc: PdfjsDocument): Promise<PdfOutlineEntry[]> {
  const tree = await doc.getOutline().catch(() => null);
  if (!tree || tree.length === 0) return [];

  const entries: PdfOutlineEntry[] = [];
  async function walk(nodes: PdfjsOutlineNode[]): Promise<void> {
    for (const node of nodes) {
      entries.push(await resolveOutlineEntry(doc, node));
      if (node.items?.length) await walk(node.items);
    }
  }
  await walk(tree);
  return entries;
}

/**
 * PDF.md §3: extracts every page's text (headers/footers stripped, columns
 * resolved, equations and figures rasterized out) plus the document's
 * outline, server-side, via pdfjs-dist. Rasterization degrades rather than
 * failing the import (§3 ⚠️) — a machine without a working canvas still
 * gets readable text, just without pictures.
 */
export async function extractPdf(buffer: Buffer): Promise<ExtractedPdf> {
  const doc = await loadDocument(buffer);

  const pageProxies: PdfjsPage[] = [];
  const rawPages: PageItems[] = [];
  for (let i = 1; i <= doc.numPages; i++) {
    const page = await doc.getPage(i);
    pageProxies.push(page);
    const viewport = page.getViewport({ scale: 1 });
    const textContent = await page.getTextContent();
    const items: RawTextItem[] = textContent.items.filter(isTextItem).map((item) => ({
      text: item.str,
      x: item.transform[4],
      y: item.transform[5],
      width: item.width,
      height: item.height || Math.abs(item.transform[3]) || 10,
      fontName: item.fontName,
    }));
    rawPages.push({ pageIndex: i - 1, width: viewport.width, height: viewport.height, items });
  }

  const stripped = stripRunningHeadersFooters(rawPages);

  // One render per page, reused for every equation/figure crop on it.
  const rasterCache = new Map<number, ReturnType<typeof renderPageToBuffer>>();
  function getRaster(pageIndex: number) {
    let cached = rasterCache.get(pageIndex);
    if (!cached) {
      cached = renderPageToBuffer(pageProxies[pageIndex]);
      rasterCache.set(pageIndex, cached);
    }
    return cached;
  }

  const pages: PdfPageContent[] = [];
  let shortPageCount = 0;

  for (const pageItems of stripped) {
    const ordered = orderPageItems(pageItems.items, pageItems.width);
    const lines = groupLines(ordered);

    const extractedChars = lines.reduce((sum, l) => sum + l.text.replace(/\s/g, "").length, 0);
    if (extractedChars < SCAN_CHAR_THRESHOLD) shortPageCount++;

    const equationBands = detectEquationBands(lines);
    const figureRegions = detectFigureRegions(lines, pageItems.width, pageItems.height);

    const needsRaster = equationBands.length > 0 || figureRegions.length > 0;
    const raster = needsRaster ? await getRaster(pageItems.pageIndex) : null;

    const equationImages = await Promise.all(
      equationBands.map((band) =>
        raster ? cropRegion(raster.png, raster.scale, raster.pageHeight, band) : Promise.resolve(null),
      ),
    );
    const figureImages = await Promise.all(
      figureRegions.map((region) =>
        raster ? cropRegion(raster.png, raster.scale, raster.pageHeight, region) : Promise.resolve(null),
      ),
    );

    const blocks = buildPageBlocks(lines, pageItems.width, pageItems.height, equationImages, figureImages);
    pages.push({ pageIndex: pageItems.pageIndex, width: pageItems.width, height: pageItems.height, blocks });
  }

  const isScan = stripped.length > 0 && shortPageCount / stripped.length > SCAN_PAGE_FRACTION;

  const outline = await extractOutline(doc);

  const metadata = await doc.getMetadata().catch(() => ({ info: {} }) as { info?: Record<string, unknown> });
  const title = typeof metadata.info?.Title === "string" && metadata.info.Title.trim() ? metadata.info.Title.trim() : null;

  return { title, outline, pages, isScan };
}
